    write(u0, *) self% eigval_min1
    write(u0, *) self% eigval_min2
    write(u0, *) self% eigval_latest

    !! ==== output these as fake nml ====
    !! why: easier to read them, but don't know which are defined a-priori
    !! init
    write(u0, *) "&strucs"
