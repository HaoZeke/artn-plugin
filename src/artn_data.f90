
#define nop(x) associate( x => x ); end associate

module artn_data

  !> @brief Module for storing the input/output data when pARTn is run through the API.
  !!
  !!


  use units, only: DP
  !! datatype encoders
  integer, parameter, public :: &
       ARTN_DTYPE_UNKNOWN = -1, &
       ARTN_DTYPE_INT     = 0, &
       ARTN_DTYPE_REAL    = 1, &
       ARTN_DTYPE_BOOL    = 2, &
       ARTN_DTYPE_STR     = 3
  !! err codes
  integer, parameter, public :: &
       ARTN_ERR_EIGVAL_LOST = -2, &
       ARTN_ERR_NUMSTEP     = -3, &
       ARTN_ERR_LARGE_ENER  = -4, &
       ARTN_ERR_OTHER       = -6

  !! filename which is used to pass serialized data
  character(*), parameter :: filename_serial = ".artn_tmpdata"

  !! signal to print on top of data dump file, used in serialize mode
  character(*), parameter :: DATADUMP_FILE_SIGNAL = "datadump_file"

  !> @brief the type t_artn_data contains copies of all data that can be exchanged with pARTn,
  !! coming from another application which calls pARTn as library (ineractive, through API).
  type :: t_artn_data

     !! ============================
     !! data for holding artn input parameters communicated from interactive mode:
     !! they can be set through the routine artn_set() from artn_api.f90.
     !! This data overwrite the working pArtn parameters -- which are located in the
     !! module artn_params -- in the routine refresh_artn()

     integer :: &
          ninit, &
          nevalf_max, &
          lanczos_max_size, &
          lanczos_min_size, &
          neigen, &
          nperp, &
          nsmooth, &
          verbose, &
          zseed, &
          nnewchance, &
          nrelax_print, &
          restart_freq

     real(DP) :: &
          push_dist_thr, &
          forc_thr, &
          eigval_thr, &
          frelax_ene_thr, &
          delr_thr, &
          lanczos_eval_conv_thr, &
          etot_diff_limit, &
          push_step_size, &
          push_step_size_per_atom, &
          lanczos_disp, &
          eigen_step_size, &
          current_step_size, &
          push_over

     !! logicals are stored as integers with 3 possible values:
     !! value 1 represents .true.
     !! value 0 represents .false.
     !! value -1 represents undefined variable
     !! logical :: &
     integer :: &
          lrestart, &
          lrelax, &
          lpush_final, &
          lmove_nextmin, &
          lnperp_limitation, &
          lanczos_at_min, &
          lanczos_always_random


     integer, allocatable :: &
          nperp_limitation(:), &
          push_ids(:)

     real(DP), allocatable :: &
          push_add_const(:,:), &
          push_init(:,:), &
          eigenvec_init(:,:)
     !! need also: eigenvec_init


     character(:), allocatable :: &
          push_mode, &
          engine_units, &
          struc_format_out, &
          push_guess, &
          eigenvec_guess, &
          filout, &
          filin, &
          initpfname, &
          eigenfname, &
          restartfname, &
          converge_property, &
          prefix_min, &
          prefix_sad


     !! ============================
     !! data generated by artn:
     !! these values get written in the routine artn_save_data( step ),
     !! depending on the value of step. The routine is called in several
     !! positions of the main artn() routine.
     !! This data can be extracted after the pArtn run via the function
     !! artn_extract() in artn_api.f90.

     ! integer ::
     ! real(DP) ::
     ! real(DP), allocatable ::
     ! integer, allocatable ::
     ! logical ::
     ! character(:), allocatable ::

     logical :: &
          has_error, &
          has_sad, &
          has_min1, &
          has_min2

     integer :: &
          error_code, &
          nevalf, &
          nevalf_sad, &
          nevalf_min1, &
          nevalf_min2, &
          inewchance, &
          nat

     real(DP) :: &
          energy_init, &
          energy_latest, &
          energy_min1, &
          energy_min2, &
          energy_sad, &
          delr_init, &
          delr_latest, &
          delr_min1, &
          delr_min2, &
          delr_sad, &
          eigval_min1, &
          eigval_min2, &
          eigval_sad, &
          eigval_latest

     integer, allocatable :: &
          typ_latest(:), &
          typ_init(:), &
          typ_min1(:), &
          typ_min2(:), &
          typ_sad(:)

     real(DP), dimension(3,3) :: &
          lat

     real(DP), allocatable :: &
          coords_latest(:,:), &
          coords_init(:,:), &
          coords_min1(:,:), &
          coords_min2(:,:), &
          coords_sad(:,:), &
          eigvec_sad(:,:), &
          eigvec_latest(:,:)

     character(:), allocatable :: &
          error_message

   contains
     procedure :: get_datatype => t_artn_get_datatype
     procedure :: get_datarank => t_artn_get_datarank
     procedure :: get_datasize => t_artn_get_datasize
     procedure :: get_data     => t_artn_get_dataval
     procedure :: dump_input   => t_artn_dump_input
     procedure :: list_set     => t_artn_list_set
     procedure :: list_extract => t_artn_list_extract
     procedure, private :: &
          set_data_int, set_data_real, set_data_logical, set_data_string, &
          set_data_int1d, set_data_real2d
          ! set_data_int2d, set_data_real1d
     generic :: set_data       => &
          set_data_int, set_data_real, set_data_logical, set_data_string, &
          set_data_int1d, set_data_real2d
          ! set_data_int2d, set_data_real1d,
     procedure :: reset_generated => t_artn_data_reset_generated
     ! procedure :: reset_init => t_artn_data_reset_init
     procedure :: read_generated => t_artn_data_read_generated
     procedure :: dump_generated => t_artn_data_dump_generated
     procedure :: serialize_input => t_artn_data_serialize_input
     final :: t_artn_data_destroy
  end type t_artn_data

  interface t_artn_data
     procedure t_artn_data_constructor
  end interface t_artn_data

contains

  !> @brief allocate new ``t_artn_data`` pointer.
  !! The name is overloaded by type name. The values are initialised
  !! such that they indicate "undetermined" values.
  !!
  !! call as:
  !!
  !! ```fortran
  !!    type( t_artn_data ), pointer :: artn_data_ptr
  !!
  !!    artn_data_ptr => t_artn_data()
  !! ```
  function t_artn_data_constructor()result(this)
    implicit none
    type( t_artn_data ), pointer :: this

    allocate( t_artn_data :: this)

    !! int
    this% ninit = -99
    this% nevalf_max = -99
    this% lanczos_max_size = -99
    this% lanczos_min_size = -99
    this% neigen = -99
    this% nperp = -99
    this% nsmooth = -99
    this% verbose = -99
    this% zseed = -99
    this% nnewchance = -99
    this% nrelax_print = -99
    this% restart_freq = -99

    !! real
    this% forc_thr                = 1e20
    this% push_dist_thr           = 1e20
    this% eigval_thr              = 1e20
    this% frelax_ene_thr          = 1e20
    this% delr_thr                = 1e20
    this% lanczos_eval_conv_thr   = 1e20
    this% etot_diff_limit         = 1e20
    this% push_step_size          = 1e20
    this% push_step_size_per_atom = 1e20
    this% lanczos_disp            = 1e20
    this% eigen_step_size         = 1e20
    this% current_step_size       = 1e20
    this% push_over               = 1e20


    !! integer representing logicals, initialize as undefined:
    this% lanczos_at_min        = -1
    this% lrestart              = -1
    this% lrelax                = -1
    this% lpush_final           = -1
    this% lmove_nextmin         = -1
    this% lnperp_limitation     = -1
    this% lanczos_always_random = -1

    !! output
    call this% reset_generated()

  end function t_artn_data_constructor

  !> @brief call reset_generated
  subroutine t_artn_data_destroy( self )
    !! destroy memory of t_artn_data instance
    implicit none
    type( t_artn_data ), intent(inout) :: self
    call self% reset_generated()
  end subroutine t_artn_data_destroy

  !> @brief reset or deallocate all data that can get generated and is held in ``t_artn_data``
  !! Set scalar values to initial.
  subroutine t_artn_data_reset_generated( self )
    !! reset or deallocate all data that can get generated
    implicit none
    class( t_artn_data ), intent(inout) :: self

    self% error_code = 0
    self% has_error = .false.
    self% has_min1 = .false.
    self% has_min2 = .false.
    self% has_sad = .false.
    self% eigval_min1 = 1e20
    self% eigval_min2 = 1e20
    self% eigval_sad = 1e20
    self% eigval_latest = 1e20

    self% nevalf = 0
    self% nevalf_sad = 0
    self% nevalf_min1 = 0
    self% nevalf_min2 = 0

    if( allocated( self% typ_latest   )) deallocate( self% typ_latest )
    if( allocated( self% coords_latest)) deallocate( self% coords_latest )
    if( allocated( self% eigvec_latest )) deallocate( self% eigvec_latest )

    if( allocated( self% typ_init     )) deallocate( self% typ_init )
    if( allocated( self% coords_init  )) deallocate( self% coords_init )

    if( allocated( self% typ_min1     )) deallocate( self% typ_min1 )
    if( allocated( self% coords_min1  )) deallocate( self% coords_min1 )

    if( allocated( self% typ_min2     )) deallocate( self% typ_min2 )
    if( allocated( self% coords_min2  )) deallocate( self% coords_min2 )

    if( allocated( self% typ_sad      )) deallocate( self% typ_sad )
    if( allocated( self% coords_sad   )) deallocate( self% coords_sad )
    if( allocated( self% eigvec_sad   )) deallocate( self% eigvec_sad )
  end subroutine t_artn_data_reset_generated

